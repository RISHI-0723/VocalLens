"""Build the VocalLens pilot dataset: synthetic fixtures + manifest + annotations.

Generates deterministic, clearly-labeled SYNTHETIC recordings (see
``vocallens.synthesis`` for the honesty note), writes ground-truth word timings
and intended flaw intervals to ``data/annotations/``, the audio to
``data/samples/``, a dataset card to ``data/README.md``, and ``data/manifest.csv``.

These are controlled fixtures for feasibility and engineering tests, NOT human
recordings. Run:  python scripts/build_dataset_manifest.py
"""
from __future__ import annotations

import csv
import hashlib
import json
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO_ROOT / "src"))

import soundfile as sf  # noqa: E402

from vocallens.synthesis import SR, VARIANTS, generate_variant  # noqa: E402
from vocallens.transcript import normalize_transcript  # noqa: E402

DATA = REPO_ROOT / "data"
SAMPLES = DATA / "samples"
ANNOTATIONS = DATA / "annotations"

# Six short English passages. Plain, license-free original sentences written for
# this project (no third-party text). Two synthetic voice profiles by parity.
PASSAGES = [
    ("p01", "The morning light moved across the quiet room."),
    ("p02", "We tested the plan and shared the results."),
    ("p03", "A clear voice carries farther than a loud one."),
    ("p04", "The bridge was built to last many winters."),
    ("p05", "She asked a careful question and waited."),
    ("p06", "Numbers alone rarely tell the whole story."),
]

# Split BY PASSAGE to avoid leakage between reference and its variants.
SPLIT = {"p01": "train", "p02": "train", "p03": "train", "p04": "train", "p05": "val", "p06": "test"}

# Intended flaw family + a provisional severity label per variant (from the
# transform, not inferred after observing model output).
VARIANT_LABELS = {
    "reference": ("none", "none"),
    "pace_fast": ("pace", "high"),
    "pace_slow": ("pace", "moderate"),
    "long_pause": ("pause", "high"),
    "monotone": ("pitch_variation", "moderate"),
    "energy_drop": ("energy_dynamics", "moderate"),
}


def transcript_hash(text: str) -> str:
    original, tokens = normalize_transcript(text)
    norm = " ".join(t.text for t in tokens)
    return hashlib.sha256(norm.encode("utf-8")).hexdigest()[:16]


def main() -> int:
    SAMPLES.mkdir(parents=True, exist_ok=True)
    ANNOTATIONS.mkdir(parents=True, exist_ok=True)

    rows = []
    for p_i, (pid, text) in enumerate(PASSAGES):
        words = [t.original for t in normalize_transcript(text)[1]]
        thash = transcript_hash(text)
        voice = "synthetic_voice_A" if p_i % 2 == 0 else "synthetic_voice_B"
        seed = 1000 + p_i
        (SAMPLES / pid).mkdir(parents=True, exist_ok=True)
        for variant in VARIANTS:
            rec = generate_variant(words, variant, seed)
            recording_id = f"{pid}_{variant}"
            rel_wav = f"samples/{pid}/{recording_id}.wav"
            sf.write(str(DATA / rel_wav), rec.samples, SR, subtype="PCM_16")

            ann = {
                "recording_id": recording_id,
                "passage_id": pid,
                "variant": variant,
                "transcript": text,
                "transcript_hash": thash,
                "word_timings": rec.word_timings,
                "flaw_intervals": rec.flaw_intervals,
                "transform_note": rec.transform_note,
                "provenance": "synthetic_tonal_fixture (generated by vocallens.synthesis)",
                "is_synthetic": True,
            }
            with (ANNOTATIONS / f"{recording_id}.json").open("w", encoding="utf-8") as fh:
                json.dump(ann, fh, indent=2)

            family, severity = VARIANT_LABELS[variant]
            rows.append({
                "recording_id": recording_id,
                "passage_id": pid,
                "role": "reference" if variant == "reference" else "participant",
                "speaker_id": voice,
                "variant": variant,
                "relative_path": rel_wav,
                "transcript_id": pid,
                "transcript_hash": thash,
                "intended_flaw_family": family,
                "intended_severity": severity,
                "recording_method": "synthetic_transform",
                "transform_note": rec.transform_note,
                "review_status": "auto_generated_by_construction",
                "annotation_notes": "Flaw intervals defined by the generating transform; not human speech.",
                "license": "CC0-1.0 (synthetic, generated by this repo)",
                "consent": "not_applicable_synthetic",
                "provenance": "vocallens.synthesis",
                "split": SPLIT[pid],
                "quality_warnings": "",
                "sample_rate_hz": SR,
                "duration_seconds": round(len(rec.samples) / SR, 4),
            })

    manifest_path = DATA / "manifest.csv"
    fieldnames = list(rows[0].keys())
    with manifest_path.open("w", encoding="utf-8", newline="") as fh:
        writer = csv.DictWriter(fh, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(rows)

    print(f"Wrote {len(rows)} recordings across {len(PASSAGES)} passages.")
    counts = {}
    for r in rows:
        counts[r["split"]] = counts.get(r["split"], 0) + 1
    print("Split counts:", counts)
    print(f"Manifest: {manifest_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
