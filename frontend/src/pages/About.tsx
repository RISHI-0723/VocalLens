import { useEffect, useState } from "react";
import { api } from "../services/api";
import type { Config } from "../types";
import { Banner, fmt } from "../components/ui";

export default function AboutPage() {
  const [cfg, setCfg] = useState<Config | null>(null);
  const [err, setErr] = useState<string | null>(null);
  useEffect(() => { api.config().then(setCfg).catch((e) => setErr(String(e.message || e))); }, []);

  return (
    <div className="grid" style={{ gap: 16 }}>
      <div className="panel">
        <h2>About &amp; methodology</h2>
        <p className="muted">
          VocalLens compares a participant recording with a reference recording of the same English
          text, localizes measurable differences in time, and explains each with its evidence. It is a
          prototype coaching/analysis tool — <strong>not</strong> a judge of ability, intent, confidence,
          or emotion. A difference may be intentional or stylistic.
        </p>
      </div>

      <div className="panel">
        <h3>Pipeline</h3>
        <p className="muted small">
          Single <code>analyze_pair()</code> contract: validate/decode → independent forced alignment
          (WhisperX optional; synthetic fixtures use <code>provided</code> ground truth) → Levenshtein
          region mapping → features (word/syllable rate, pauses, pitch semitone-IQR, within-recording
          relative energy dBFS, MFCC diagnostics) → detection (normalized exceedance R=D/T, severity
          bands, grouping) → evidence quality (Q=0.35A+0.30F+0.20S+0.15M) → prototype rubric scoring.
          The dashboard calls this engine via FastAPI and never recomputes analysis in the browser.
        </p>
      </div>

      {err && <div className="panel"><Banner kind="error">Could not load config: {err}</Banner></div>}
      {cfg && (
        <div className="panel">
          <h3>Configuration &amp; provenance</h3>
          <div className="small kv">
            analysis_config_hash: <code>{cfg.analysis_config_hash}</code><br />
            scoring_config_hash: <code>{cfg.scoring_config_hash}</code><br />
            language: <code>{cfg.language}</code> · overall needs ≥ {cfg.overall_min_valid_dimensions} valid dimensions
          </div>
          <h4 style={{ marginBottom: 6 }}>Detection thresholds</h4>
          <table>
            <thead><tr><th>rule</th><th>threshold</th><th>unit</th></tr></thead>
            <tbody>
              {Object.entries(cfg.thresholds).map(([k, v]) => (
                <tr key={k}><td>{k}</td><td>{fmt(v.value, 3)}</td><td className="muted">{v.unit}</td></tr>
              ))}
            </tbody>
          </table>
          <div className="small muted" style={{ marginTop: 6 }}>
            Severity: low R&lt;{cfg.severity_bands.low_upper_ratio}, moderate &lt;{cfg.severity_bands.moderate_upper_ratio}, else high.
          </div>
        </div>
      )}

      <div className="panel">
        <h3>Known limitations (preserved, honest)</h3>
        <ul className="muted small">
          <li>The dataset is <strong>100% synthetic</strong> tonal fixtures (CC0, generated by <code>vocallens.synthesis</code>); it is not natural speech and does not demonstrate generalization.</li>
          <li>Synthetic evaluation does <strong>not</strong> establish natural-speech accuracy.</li>
          <li><strong>Real-speech alignment accuracy is NOT VERIFIED</strong> — no licensed/consented real speech and reviewed transcript available.</li>
          <li>Forced alignment maps a supplied transcript to audio; it does <strong>not</strong> verify the transcript is correct.</li>
          <li>MFCC diagnostics are visualization aids, not proof of a delivery flaw.</li>
          <li>A difference from the reference is <strong>not</strong> automatically a flaw.</li>
          <li><strong>Energy-dynamics recall is 0.0</strong> on the current synthetic pilot (the within-recording <code>z_rel</code> metric is invariant to uniform loudness changes by design).</li>
          <li>Missing evidence is reported as <strong>Unavailable</strong>, never 0.</li>
          <li>Scores are a provisional prototype rubric, not a validated measure of speaking quality.</li>
        </ul>
      </div>

      <div className="panel">
        <h3>Reproducibility</h3>
        <pre className="small" style={{ whiteSpace: "pre-wrap" }}>
{`# backend + engine
pip install -r requirements.txt
python scripts/build_dataset_manifest.py
python scripts/validate_dataset.py
python -m pytest -q
python scripts/run_evaluation.py --split test
uvicorn api.main:app --port 8000

# frontend
cd frontend && npm install && npm run dev   # or: npm run build`}
        </pre>
      </div>
    </div>
  );
}
